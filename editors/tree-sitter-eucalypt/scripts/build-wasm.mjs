#!/usr/bin/env node
// Build tree-sitter-eucalypt.wasm and record what it was built from in
// wasm-manifest.json (eu-ioz21.5).
//
// Run from editors/tree-sitter-eucalypt with `npm run build-wasm`. It uses the
// tree-sitter CLI pinned in package-lock.json, which compiles with emcc when it
// is on PATH and otherwise with its pinned emscripten/emsdk image under docker
// or podman. With the pinned CLI and image the output is byte-reproducible.
//
// `npm run build-wasm -- --check` rebuilds into a temporary file and fails if
// it differs from the committed WASM or the manifest is stale.

import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const WASM = "tree-sitter-eucalypt.wasm";
const MANIFEST = "wasm-manifest.json";
const check = process.argv.includes("--check");

const sha256 = (bytes) => createHash("sha256").update(bytes).digest("hex");
const read = (rel) => readFileSync(join(root, rel));

// The C sources the WASM is compiled from: src/*.c and src/tree_sitter/*.h.
function sourceFiles() {
  const c = readdirSync(join(root, "src")).filter((f) => f.endsWith(".c")).map((f) => `src/${f}`);
  const h = readdirSync(join(root, "src/tree_sitter"))
    .filter((f) => f.endsWith(".h"))
    .map((f) => `src/tree_sitter/${f}`);
  return [...c, ...h].sort();
}

function cliVersion() {
  const out = execFileSync("npx", ["--no-install", "tree-sitter", "--version"], { cwd: root });
  return out.toString().trim().split(/\s+/)[1];
}

function lockedVersion(pkg) {
  const lock = JSON.parse(read("package-lock.json"));
  return lock.packages[`node_modules/${pkg}`].version;
}

function abiVersion() {
  const m = /#define LANGUAGE_VERSION (\d+)/.exec(read("src/parser.c").toString());
  return Number(m[1]);
}

// The emscripten version each supported CLI compiles with (its emsdk image
// tag, from cli/loader/emscripten-version in the tree-sitter source). Bumping
// tree-sitter-cli means adding its entry here.
const EMSCRIPTEN_FOR_CLI = { "0.22.6": "3.1.55" };

function emscriptenVersion(cli) {
  const v = EMSCRIPTEN_FOR_CLI[cli];
  if (!v) throw new Error(`no emscripten version recorded for tree-sitter CLI ${cli}`);
  return v;
}

function build(outPath) {
  execFileSync("npx", ["--no-install", "tree-sitter", "build", "--wasm", "-o", outPath], {
    cwd: root,
    stdio: "inherit",
  });
  return readFileSync(outPath);
}

function manifest(wasmBytes) {
  const pkg = JSON.parse(read("package.json"));
  const cli = cliVersion();
  if (cli !== lockedVersion("tree-sitter-cli")) {
    throw new Error(`tree-sitter CLI ${cli} is not the locked ${lockedVersion("tree-sitter-cli")}; run npm ci`);
  }
  return {
    comment:
      "Generated by scripts/build-wasm.mjs (npm run build-wasm). Do not edit. " +
      "The WASM pairs with queries/highlights.scm at the same eucalypt revision.",
    grammar: pkg.name,
    grammar_version: pkg.version,
    abi_version: abiVersion(),
    tree_sitter_cli: cli,
    emscripten: emscriptenVersion(cli),
    web_tree_sitter: lockedVersion("web-tree-sitter"),
    wasm: { file: WASM, sha256: sha256(wasmBytes), bytes: wasmBytes.length },
    sources: Object.fromEntries(sourceFiles().map((f) => [f, sha256(read(f))])),
  };
}

const json = (m) => JSON.stringify(m, null, 2) + "\n";

if (check) {
  const dir = mkdtempSync(join(tmpdir(), "ts-eu-wasm-"));
  try {
    const fresh = build(join(dir, WASM));
    const problems = [];
    if (!fresh.equals(read(WASM))) problems.push(`${WASM} differs from a fresh build`);
    if (json(manifest(fresh)) !== read(MANIFEST).toString()) problems.push(`${MANIFEST} is stale`);
    if (problems.length) {
      console.error(problems.join("\n") + "\nRun `npm run build-wasm` and commit the result.");
      process.exit(1);
    }
    console.log(`${WASM} and ${MANIFEST} match a fresh build.`);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
} else {
  const bytes = build(join(root, WASM));
  writeFileSync(join(root, MANIFEST), json(manifest(bytes)));
  console.log(`Wrote ${WASM} (${bytes.length} bytes) and ${MANIFEST}.`);
}
